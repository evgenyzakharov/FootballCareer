export const CLUBS: Club[] = TABLE.flatMap(([leagueId, seeds]) => {
  const league = getLeague(leagueId)
  return seeds.map(([id, ru, en, tier]) => ({
    id,
    name: { ru, en },
    leagueId,
    country: league.country,
    confederation: league.confederation,
    tier,
  }))
})

const BY_ID = new Map(CLUBS.map((c) => [c.id, c]))

export function getClub(id: string): Club {
  const club = BY_ID.get(id)
  if (!club) throw new Error(`Unknown club: ${id}`)
  return club
}

export function findClub(id: string | null | undefined): Club | null {
  return id ? BY_ID.get(id) ?? null : null
}

export function clubsInCountry(country: string): Club[] {
  return CLUBS.filter((c) => c.country === country)
}

export function clubsByTier(min: number, max: number): Club[] {
  return CLUBS.filter((c) => c.tier >= min && c.tier <= max)
}
